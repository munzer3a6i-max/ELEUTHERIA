// Gets the migrations into the Supabase project, either way you prefer.
//
//   node scripts/apply-migrations.mjs
//     Bundles every migration into db/bundle.sql for pasting into the SQL
//     editor at Supabase, Project, SQL Editor. Nothing is sent anywhere.
//
//   SUPABASE_DB_URL='postgresql://...' node scripts/apply-migrations.mjs --apply
//     Applies them directly. The connection string is at Supabase, Project
//     Settings, Database, Connection string, and it contains the database
//     password, so pass it on the command line or through the environment --
//     never into a file in this repository.
//
// Each file runs inside its own transaction and is recorded in
// ops.schema_migrations, so running this twice does not run anything twice.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { createRequire } from 'node:module'

const files = readdirSync('db/migrations').filter((f) => f.endsWith('.sql')).sort()
const apply = process.argv.includes('--apply')
const url = process.env.SUPABASE_DB_URL

if (!apply || !url) {
  const bundle = [
    '-- Eleutheria: every migration, in order.',
    '-- Paste this whole file into the Supabase SQL editor and run it once.',
    '-- Generated by scripts/apply-migrations.mjs; edit the files in db/migrations instead.',
    '',
    ...files.map((file) => `\n-- ======================================================== ${file} --\n\n${readFileSync(`db/migrations/${file}`, 'utf8')}`),
  ].join('\n')
  writeFileSync('db/bundle.sql', bundle)
  console.log(`Bundled ${files.length} migration(s) into db/bundle.sql (${bundle.split('\n').length} lines).\n`)
  console.log('Next: open Supabase, your project, SQL Editor, paste the file, run it.')
  console.log('Then: Project Settings, API, Exposed schemas — add `ops` beside `public`.\n')
  if (apply && !url) console.log('(--apply needs SUPABASE_DB_URL, so the bundle was written instead.)')
  process.exit(0)
}

// Direct application needs a Postgres driver, which is not a dependency of the
// app itself.
let Client
try {
  Client = createRequire(import.meta.url)('pg').Client
} catch {
  console.error('Install the driver first:  npm i -D pg --no-save')
  process.exit(1)
}

const client = new Client({ connectionString: url, ssl: { rejectUnauthorized: false } })
await client.connect()
console.log(`connected to ${url.replace(/:[^:@/]+@/, ':****@')}\n`)

await client.query(`
  create schema if not exists ops;
  create table if not exists ops.schema_migrations (
    filename   text primary key,
    applied_at timestamptz not null default now()
  );
`)

const done = new Set((await client.query('select filename from ops.schema_migrations')).rows.map((r) => r.filename))

for (const file of files) {
  if (done.has(file)) {
    console.log(`skipped  ${file}  (already applied)`)
    continue
  }
  const sql = readFileSync(`db/migrations/${file}`, 'utf8')
  try {
    await client.query('begin')
    await client.query(sql)
    await client.query('insert into ops.schema_migrations (filename) values ($1)', [file])
    await client.query('commit')
    console.log(`applied  ${file}`)
  } catch (error) {
    await client.query('rollback')
    console.error(`\nFAILED   ${file}\n${error.message}\n`)
    console.error('Nothing from that file was applied. Fix it and run again.')
    await client.end()
    process.exit(1)
  }
}

console.log('\nDone. Now add `ops` to Project Settings, API, Exposed schemas.')
await client.end()
